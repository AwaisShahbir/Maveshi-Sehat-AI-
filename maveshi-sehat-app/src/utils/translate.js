/**
 * Checks if a string contains Urdu/Arabic characters
 */
export const isUrduText = (text) => {
  if (typeof text !== 'string') return false;
  return /[\u0600-\u06FF\u0750-\u077F\uFB50-\uFDFF\uFE70-\uFEFF]/.test(text);
};

